package com.finsight.finsight_api.prediction;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.List;
import java.util.Map;

/** What the frontend receives. */
public record PredictionDto(
        Long id,
        Long companyId,
        BigDecimal riskScore,
        String riskLevel,
        BigDecimal cashflowProjection,
        /** Full factor list (feature, impact, value). */
        List<ShapFactorDto> shapExplanation,
        /** Same impacts as a feature -> impact map, the shape the current frontend type expects. */
        Map<String, Double> shapValues,
        /** Alerts generated by business rules. Empty until that module is built. */
        List<String> generatedAlerts,
        String modelVersion,
        LocalDateTime predictionDate,
        /** "improving" | "worsening" | "stable" | null, según la trayectoria real de las transacciones. */
        String trend,
        BigDecimal projectedCashflow30d,
        BigDecimal projectedCashflow90d,
        /** Días estimados hasta quedarse sin fondos si la tendencia negativa continúa; null si no aplica. */
        Integer estimatedDaysToDepletion
) {
}
